/**
 * Returns the outbreak disease name strictly in the prescribed language.
 */
export function getDiseaseName(rawDisease: string | undefined, langCode: string = 'en'): string {
  if (!rawDisease) return '';
  const lang = (langCode || 'en').toLowerCase().split('-')[0];
  const lower = rawDisease.toLowerCase();

  let key: string | null = null;
  if (lower.includes('armyworm') || lower.includes('spodoptera') || lower.includes('आर्मीवर्म') || lower.includes('లద్దెపురుగు') || lower.includes('படைப்புழு')) {
    key = 'fall_armyworm';
  } else if (lower.includes('bollworm') || lower.includes('pectinophora') || lower.includes('गुलाबी सुंडी') || lower.includes('గులాబీ') || lower.includes('இளஞ்சிவப்பு')) {
    key = 'pink_bollworm';
  } else if (lower.includes('early blight') || lower.includes('leaf curl') || lower.includes('अगेती') || lower.includes('ఆకు ముడత') || lower.includes('இலைச்சுருட்டல்')) {
    key = 'early_blight';
  } else if (lower.includes('bacterial') || lower.includes('blb') || lower.includes('जीवाणु') || lower.includes('బ్యాక్టీరియల్') || lower.includes('பாக்டீரியா')) {
    key = 'bacterial_leaf_blight';
  } else if (lower.includes('thrips') || lower.includes('murda') || lower.includes('थ्रिप्स') || lower.includes('మరడా') || lower.includes('తామర') || lower.includes('இலைப்பேன்')) {
    key = 'thrips_murda';
  }

  if (key && DISEASE_NAMES_DICTIONARY[key]) {
    const dict = DISEASE_NAMES_DICTIONARY[key];
    return dict[lang] || dict['en'] || rawDisease;
  }

  // Fallback
  if (lang === 'en') {
    let clean = rawDisease.split('/')[0].trim();
    clean = clean.replace(/\([^)]*[\u0900-\u0D7F][^)]*\)/g, '').trim();
    return cleanEnglishText(clean);
  }

  return resolveBilingualString(rawDisease, langCode).display;
}

